package basic;

public class t1 {
    public static void main(String[] args){
        //整数
        System.out.println(666);

        //小数
        System.out.println(6.76);

        //字符
        System.out.println("gdgid");

        //布尔
        System.out.println(true);

        //空,不能直接打印，需要转成字符串形式
        System.out.printf("%-8s%s%n", "name3f44", "age");
        System.out.printf("%-8s%s%n", "tom", "23");
    }
}
